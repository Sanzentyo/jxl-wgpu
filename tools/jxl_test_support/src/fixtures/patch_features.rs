impl Family {
    pub fn suffixes(&self) -> impl Iterator<Item = &'static str> {
        self.zero_noise
            .then_some("_zero")
            .into_iter()
            .chain(["_empty", ""])
            .chain(
                self.inject_noise
                    .then_some(["_noise_empty", "_noise"])
                    .into_iter()
                    .flatten(),
            )
            .chain(
                self.padded
                    .then_some(["_padded", "_padded_noise"])
                    .into_iter()
                    .flatten(),
            )
            .chain(self.chain.then_some("_chain"))
    }
}
